package Task11Adapter;

public class MetricBox {
    private final double widthCm;
    private final double heightCm;
    public MetricBox(double widthCm, double heightCm) { this.widthCm = widthCm; this.heightCm = heightCm; }
    public double getWidthCm() { return widthCm; }
    public double getHeightCm() { return heightCm; }
}
